// Screenshot tour with headless Chrome. Needs the dev server (npm run dev) or preview on URL (default http://127.0.0.1:5173/).
import puppeteer from "puppeteer-core";
import fs from "node:fs";
const URL = process.env.URL || "http://127.0.0.1:5173/";
const OUT = "screenshots";
fs.mkdirSync(OUT, { recursive: true });
const only = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: process.env.CHROME || "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist", "--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 720, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error" && !/status of 500/.test(m.text())) errors.push(m.text()); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (name) => { if (only.length && !only.includes(name)) return; await page.screenshot({ path: `${OUT}/${name}.png` }); console.log("shot", name); };
const ev = (fn, ...a) => page.evaluate(fn, ...a);
await page.goto(URL, { waitUntil: "load" });
await page.waitForFunction(() => window.__game && window.__game.scene.isActive("title"), { timeout: 60000 });
await sleep(1200);
await shot("01-title");
await page.keyboard.press("Enter");
await page.waitForFunction(() => window.__ev && window.__ev.ready, { timeout: 60000 });
await sleep(1500);
await shot("02-start-cottage");
const warp = async (a, x, y, d = "down") => { await ev((a, x, y, d) => window.__ev.warp(a, x, y, d), a, x, y, d); await sleep(900); };
await ev(() => window.__ev.give("keeper_blade"));
await ev(() => window.__ev.give("wicker_buckler"));
await warp("world", 47, 40.5);
await sleep(1800);
await shot("03-village");
// dialogue with the warden
await ev(() => window.__ev.patch((s) => s.talk("isolde")));
await sleep(1500);
await shot("04-dialogue");
await ev(() => window.__ev.patch((s) => { s.dialog = null; s.mode = "play"; }));
await warp("world", 20, 20);
await sleep(1500);
await shot("05-wood");
await warp("world", 82, 14);
await sleep(1500);
await shot("06-beacon-hall");
await warp("world", 100, 70);
await sleep(1500);
await shot("07-lake");
await warp("world", 14, 62); await sleep(1200);
await shot("23-water-animation-a"); await sleep(450); await shot("24-water-animation-b");
await warp("world", 49, 45); await sleep(900);
await shot("25-kit-npc");
await ev(() => window.__ev.warp("cistern_r5", 12, 10, "down")); await sleep(1400);
await shot("26-dark-room");
// combat: spawn a slime and a bat next to the player and swing
await warp("world", 47, 44);
await ev(() => window.__ev.patch((s) => { s.enemies.push(s.makeEnemy("slime", s.p.x + 28, s.p.y + 4, "1,1"), s.makeEnemy("bat", s.p.x - 26, s.p.y - 10, "1,1"), s.makeEnemy("soldier", s.p.x + 10, s.p.y + 34, "1,1")); }));
await sleep(500);
await page.keyboard.down("Space"); await sleep(80); await page.keyboard.up("Space");
await sleep(110);
await shot("08-sword-swing");
await sleep(900);
await page.keyboard.down("Space"); await sleep(1100);
await shot("09-spin-charge");
await page.keyboard.up("Space");
await sleep(200);
await shot("10-spin");
await sleep(1500);
await ev(() => window.__ev.give("gale_disc"));
await warp("cistern_r1", 12, 13);
await sleep(1500);
await shot("11-dungeon-entry");
await warp("cistern_r4", 12, 12);
await sleep(1500);
await shot("12-dungeon-gallery");
await warp("cistern_r7", 12, 12);
await sleep(1300);
await shot("13-dungeon-big-chest");
await warp("cistern_r8", 12, 12);
await ev(() => window.__ev.patch((s) => { s.save.items.push("cistern_map", "cistern_compass"); s.bossActive = "sluicejaw"; }));
await sleep(2200);
await shot("14-boss");
await ev(() => window.__ev.openMenu("Map"));
await sleep(600);
await shot("15-dungeon-map");
await ev(() => window.__ev.closeMenu());
await warp("world", 47, 44);
await ev(() => window.__ev.openMenu("Map"));
await sleep(600);
await shot("16-world-map");
await ev(() => window.__ev.openMenu("Quests"));
await sleep(400);
await shot("17-quests");
await ev(() => window.__ev.openMenu("Items"));
await sleep(400);
await shot("18-items");
await ev(() => window.__ev.closeMenu());
await warp("lamp_shop", 8, 8);
await ev(() => window.__ev.patch((s) => { s.openShop(); }));
await sleep(600);
await shot("19-shop");
await ev(() => window.__ev.patch((s) => { s.closeShop(); }));
// touch overlay on a phone-sized viewport (fresh page so the layout is built for that size)
await page.close();
const phone = await browser.newPage();
await phone.setViewport({ width: 844, height: 390, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
phone.on("pageerror", (e) => errors.push(String(e)));
await phone.goto(URL, { waitUntil: "load" });
await phone.waitForFunction(() => window.__game && window.__game.scene.isActive("title"), { timeout: 60000 });
await sleep(800);
await phone.keyboard.press("Enter");
await phone.waitForFunction(() => window.__ev && window.__ev.ready, { timeout: 60000 });
await phone.evaluate(async () => { window.__ev.give("keeper_blade"); await window.__ev.warp("world", 47, 44); });
await sleep(1500);
if (!only.length || only.includes("20-touch-phone")) { await phone.screenshot({ path: `${OUT}/20-touch-phone.png` }); console.log("shot 20-touch-phone"); }
console.log(errors.length ? "PAGE ERRORS:\n" + [...new Set(errors)].slice(0, 12).join("\n") : "no page errors");
await browser.close();
process.exit(errors.length ? 1 : 0);
