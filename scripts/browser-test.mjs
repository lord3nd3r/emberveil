// Real-browser input test: drives the running game with real keyboard and mouse events through headless Chrome.
// Needs the dev server or preview on URL. Exits non-zero on any failed expectation or page error.
import puppeteer from "puppeteer-core";
const URL = process.env.URL || "http://127.0.0.1:5173/";
const browser = await puppeteer.launch({ executablePath: process.env.CHROME || "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage();
await page.setViewport({ width: 1100, height: 650 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error" && !/status of 500/.test(m.text())) errors.push(m.text()); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = "") => { console.log(cond ? "ok  " : "FAIL", name, cond ? "" : extra); if (!cond) fails++; };
const st = () => page.evaluate(() => { const s = window.__ev.sim; return { x: s.p.x, y: s.p.y, state: s.p.state, facing: s.p.facing, mode: s.mode, hp: s.hp, area: s.area.id, magic: s.save.magic, enemies: s.enemies.length, dialog: !!s.dialog, shield: s.p.shielding, equipped: s.save.equipped }; });
await page.evaluateOnNewDocument(() => localStorage.clear());
await page.goto(URL, { waitUntil: "load" });
await page.waitForFunction(() => window.__game && window.__game.scene.isActive("title"), { timeout: 60000 });
await sleep(800);
await page.keyboard.press("Enter");
await page.waitForFunction(() => window.__ev && window.__ev.ready, { timeout: 60000 });
await sleep(800);
await page.evaluate(() => { window.__ev.give("keeper_blade"); window.__ev.give("wicker_buckler"); window.__ev.give("gale_disc"); return window.__ev.warp("world", 47, 44); });
await sleep(800);
let a = await st();
await page.keyboard.down("KeyD"); await sleep(600); await page.keyboard.up("KeyD");
let b = await st();
ok("D key moves the hero right", b.x > a.x + 20 && b.facing === "right", JSON.stringify({ a, b }));
await page.keyboard.down("ArrowUp"); await sleep(500); await page.keyboard.up("ArrowUp");
let c = await st();
ok("Arrow up moves the hero up", c.y < b.y - 15 && c.facing === "up");
await page.keyboard.down("KeyS"); await page.keyboard.down("KeyD"); await sleep(400);
let dg = await st();
await page.keyboard.up("KeyS"); await page.keyboard.up("KeyD");
ok("diagonal movement works", dg.x > c.x + 8 && dg.y > c.y + 8);
await page.keyboard.press("Space");
await sleep(90);
ok("Space swings the sword", (await st()).state === "swing");
await sleep(500);
await page.keyboard.down("ShiftLeft"); await sleep(150);
ok("Shift raises the shield", (await st()).shield === true);
await page.keyboard.up("ShiftLeft"); await sleep(100);
await page.keyboard.down("KeyD"); await page.keyboard.press("KeyL"); await sleep(120);
ok("L rolls", (await st()).state === "roll");
await page.keyboard.up("KeyD"); await sleep(500);
await page.keyboard.down("Space"); await sleep(1300);
ok("holding the sword button charges", (await st()).state === "charge");
await page.keyboard.up("Space"); await sleep(120);
ok("releasing a full charge spins", (await st()).state === "spin");
await sleep(600);
const m0 = (await st()).magic;
await page.keyboard.press("KeyQ"); await sleep(150);
ok("Q throws the Gale Disc (spends magic)", (await st()).magic < m0 - 2);
await sleep(800);
// mouse: aim and swing toward the pointer
await page.mouse.move(300, 300);
await page.mouse.move(520, 330);
await page.mouse.down(); await sleep(80); await page.mouse.up();
ok("left click swings", ["swing", "idle"].includes((await st()).state));
await sleep(500);
// menu
await page.keyboard.press("Escape"); await sleep(300);
ok("Esc opens the pause menu", await page.evaluate(() => window.__game.scene.getScene("game").menu.open));
await page.keyboard.press("ArrowRight"); await sleep(150);
await page.keyboard.press("Escape"); await sleep(300);
ok("Esc closes it", !(await page.evaluate(() => window.__game.scene.getScene("game").menu.open)));
await page.keyboard.press("KeyM"); await sleep(300);
ok("M opens the map", await page.evaluate(() => window.__game.scene.getScene("game").menu.open));
await page.keyboard.press("KeyM"); await sleep(200);
// talk to an NPC through the real interact key
await page.evaluate(async () => { await window.__ev.warp("world", 47, 40.5); const s = window.__ev.sim; const n = s.things.find((t) => t.id === "isolde"); s.p.x = n.x - 12; s.p.y = n.y + 6; s.p.facing = "right"; });
await sleep(300);
await page.keyboard.press("KeyE"); await sleep(400);
ok("E talks to a nearby person", (await st()).dialog === true);
for (let i = 0; i < 12 && (await st()).dialog; i++) { await page.keyboard.press("KeyE"); await sleep(250); await page.keyboard.press("KeyE"); await sleep(250); }
ok("dialogue can be dismissed with E", !(await st()).dialog);
// level-up effect: pillar, rings, sparkles, glow and the floating label; calmer under reduced motion; all cleaned up afterwards
await page.evaluate(async () => { await window.__ev.warp("world", 47, 40.5); window.__settings.update({ reduceMotion: false, reduceFlash: false }); });
await sleep(300);
const lvl0 = await page.evaluate(() => window.__ev.sim.level);
await page.evaluate(() => window.__ev.sim.addXp(window.__ev.sim.xpProgress().need));
await sleep(350);
const fxFull = await page.evaluate(() => ({ n: window.__ev.fxCount, lvl: window.__ev.sim.level, label: window.__game.scene.getScene("game").children.list.some((c) => c.text === "LEVEL UP!") }));
ok("level-up shows the full effect (pillar, rings, sparkles, glow, label)", fxFull.lvl === lvl0 + 1 && fxFull.n >= 20 && fxFull.label, JSON.stringify(fxFull));
await page.screenshot({ path: "screenshots/21-level-up.png" });
await sleep(3300);
ok("level-up effect objects are all cleaned up", (await page.evaluate(() => window.__ev.fxCount)) === 0);
await page.evaluate(() => window.__settings.update({ reduceMotion: true }));
await page.evaluate(() => window.__ev.sim.addXp(window.__ev.sim.xpProgress().need));
await sleep(350);
const fxCalm = await page.evaluate(() => ({ n: window.__ev.fxCount, label: window.__game.scene.getScene("game").children.list.some((c) => c.text === "LEVEL UP!") }));
ok("reduced motion: only the label and a soft glow", fxCalm.n <= 3 && fxCalm.label, JSON.stringify(fxCalm));
await page.screenshot({ path: "screenshots/22-level-up-calm.png" });
await page.evaluate(() => window.__settings.update({ reduceMotion: false }));
await sleep(1500);
// save/load round trip through localStorage
await sleep(200);
await page.evaluate(() => window.__ev.sim.commit());
const saved = await page.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith("emberveil-save-v1")));
ok("a save is written to this device", saved.length === 1, JSON.stringify(saved));
console.log(errors.length ? "PAGE ERRORS:\n" + [...new Set(errors)].slice(0, 10).join("\n") : "no page errors");
ok("no page errors", errors.length === 0);
await browser.close();
console.log(fails ? `${fails} browser check(s) FAILED` : "browser input test passed");
process.exit(fails ? 1 : 0);
